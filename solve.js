// Fast drop-in for makefun-site 1.0.0 (site-generator-speed-01-run-20261122).
//
// A from-scratch reimplementation of makefun-site's build, written in this
// session from the kit's reference code as the behaviour specification.
// Same answers byte for byte; faster by removing the reference's
// intermediate work, not by changing any rule:
//
//   - Markdown is rendered in one pass over the source's lines: no token
//     array, no second split of the body, no per-line regex battery.
//     Blocks are classified by their first character; a regex runs only
//     where the line's shape already suggests that block.
//   - Inline rendering scans once with a chunk flush: plain runs are
//     copied whole, never escaped one character at a time.
//   - slugify takes an ASCII fast path (NFKD is the identity on ASCII and
//     ASCII holds no combining marks); the slow path is the reference's.
//   - Word counting scans without building a match array.
//   - Templates parse exactly as the reference does; rendering reuses one
//     scope/loop object per for-render instead of one closure per element
//     (rendering is synchronous, so nothing observes the reuse).
//
// No imports, no cache between cases: every case is answered alone.

const REPORT_FILE = 'build-report.txt';
const RESERVED = Object.freeze(['posts', 'tags', 'page']);
const INCLUDE_DEPTH = 8;

const byCodeUnits = (a, b) => (a < b ? -1 : a > b ? 1 : 0);

// ---------------------------------------------------------------- text

const ESCAPES = { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' };

function escapeHtml(text) {
  return text.replace(/[&<>"']/g, (c) => ESCAPES[c]);
}

const SLUG_MAX = 64;

function slugifySlow(text) {
  const plain = text.normalize('NFKD').replace(/\p{M}/gu, '');
  let out = '';
  let gap = false;
  for (const ch of plain) {
    let keep = null;
    if (ch >= 'A' && ch <= 'Z') keep = ch.toLowerCase();
    else if ((ch >= 'a' && ch <= 'z') || (ch >= '0' && ch <= '9')) keep = ch;
    if (keep === null) {
      gap = out.length > 0;
      continue;
    }
    if (gap) out += '-';
    gap = false;
    out += keep;
  }
  out = out.slice(0, SLUG_MAX).replace(/-+$/, '');
  return out === '' ? 'untitled' : out;
}

/** The slug of `text`; identical to the reference's slugify. */
function slugify(text) {
  // NFKD is the identity on ASCII and ASCII holds no combining marks, so a
  // purely-ASCII string can skip the normalisation and the mark strip.
  let ascii = true;
  for (let i = 0; i < text.length; i++) {
    if (text.charCodeAt(i) >= 128) {
      ascii = false;
      break;
    }
  }
  if (!ascii) return slugifySlow(text);
  let out = '';
  let gap = false;
  for (let i = 0; i < text.length; i++) {
    const ch = text[i];
    let keep = null;
    if (ch >= 'A' && ch <= 'Z') keep = ch.toLowerCase();
    else if ((ch >= 'a' && ch <= 'z') || (ch >= '0' && ch <= '9')) keep = ch;
    if (keep === null) {
      gap = out.length > 0;
      continue;
    }
    if (gap) out += '-';
    gap = false;
    out += keep;
  }
  out = out.slice(0, SLUG_MAX).replace(/-+$/, '');
  return out === '' ? 'untitled' : out;
}

function uniqueSlug(slug, taken) {
  let out = slug;
  for (let n = 2; taken.has(out); n++) out = `${slug}-${n}`;
  taken.add(out);
  return out;
}

const MONTHS = ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December'];

function longDate(date) {
  const [y, m, d] = date.split('-');
  return `${Number(d)} ${MONTHS[Number(m) - 1]} ${y}`;
}

// ---------------------------------------------------------------- front matter

const KEYS = Object.freeze(['title', 'date', 'tags', 'draft', 'layout', 'slug', 'summary']);

const LINE = /^([a-z_]+):(?: (.*))?$/;
const DATE = /^(\d{4})-(\d{2})-(\d{2})$/;
const NAME = /^[a-z0-9-]+$/;
const SLUG = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;
const TAG = /^[^"[\]]+$/;

function daysIn(y, m) {
  if (m === 2) return (y % 4 === 0 && y % 100 !== 0) || y % 400 === 0 ? 29 : 28;
  return [4, 6, 9, 11].includes(m) ? 30 : 31;
}

function stringOf(raw) {
  if (raw.startsWith('"')) {
    if (raw.length < 2 || !raw.endsWith('"')) return { error: 'a quoted string is not closed' };
    let out = '';
    for (let i = 1; i < raw.length - 1; i++) {
      const c = raw[i];
      if (c === '\\') {
        const n = raw[i + 1];
        if ((n !== '"' && n !== '\\') || i + 1 === raw.length - 1) return { error: 'a quoted string holds an escape other than \\" or \\\\' };
        out += n;
        i++;
      } else if (c === '"') return { error: 'a quoted string holds a stray quote' };
      else out += c;
    }
    return { value: out };
  }
  if (raw.startsWith('[')) return { error: 'a bare string opens on [' };
  return { value: raw };
}

function valueOf(key, raw) {
  switch (key) {
    case 'title':
    case 'summary': {
      const s = stringOf(raw);
      return 'error' in s ? { error: `key "${key}": ${s.error}` } : s;
    }
    case 'date': {
      const m = DATE.exec(raw);
      const y = m ? Number(m[1]) : 0;
      const mo = m ? Number(m[2]) : 0;
      const d = m ? Number(m[3]) : 0;
      if (!m || y < 1970 || y > 2099 || mo < 1 || mo > 12 || d < 1 || d > daysIn(y, mo)) return { error: 'key "date": not a date from 1970-01-01 to 2099-12-31 (YYYY-MM-DD)' };
      return { value: raw };
    }
    case 'tags': {
      if (!raw.startsWith('[') || !raw.endsWith(']')) return { error: 'key "tags": not a list [a, b]' };
      const inner = raw.slice(1, -1);
      if (inner.trim() === '') return { value: [] };
      const tags = inner.split(',').map((t) => t.trim());
      if (tags.some((t) => t === '' || !TAG.test(t))) return { error: 'key "tags": an empty tag, or one holding " [ or ]' };
      return { value: tags };
    }
    case 'draft':
      return raw === 'true' ? { value: true } : raw === 'false' ? { value: false } : { error: 'key "draft": true or false' };
    case 'layout':
      return NAME.test(raw) ? { value: raw } : { error: 'key "layout": not a template name' };
    case 'slug':
      return SLUG.test(raw) && raw.length <= 64 ? { value: raw } : { error: 'key "slug": not a slug' };
    default:
      return { error: `unknown key "${key}"` };
  }
}

/**
 * A source's front matter, read from its lines: { data, bodyStart }, or
 * { error } with the first reason it is refused. `lines` is the source's
 * text split on "\n" (line ends already made "\n").
 */
function parseFrontMatterLines(lines) {
  if (lines[0] !== '---') return { error: 'no front matter' };
  let close = -1;
  for (let i = 1; i < lines.length; i++) {
    if (lines[i] === '---') {
      close = i;
      break;
    }
  }
  if (close === -1) return { error: 'the front matter is not closed' };
  const data = {};
  for (let i = 1; i < close; i++) {
    const line = lines[i];
    if (/^[ \t]*$/.test(line) || line.startsWith('#')) continue;
    const m = LINE.exec(line);
    if (!m) return { error: `line ${i + 1} is not "key: value"` };
    const key = m[1];
    const raw = (m[2] ?? '').replace(/[ \t]+$/, '');
    if (!KEYS.includes(key)) return { error: `unknown key "${key}"` };
    if (Object.hasOwn(data, key)) return { error: `key "${key}" is given twice` };
    if (raw === '') return { error: `key "${key}" has no value` };
    const v = valueOf(key, raw);
    if ('error' in v) return v;
    data[key] = v.value;
  }
  if (!Object.hasOwn(data, 'title')) return { error: 'no title' };
  return { data, bodyStart: close + 1 };
}

// ---------------------------------------------------------------- markdown

const isSpaceTab = (c) => c === ' ' || c === '\t';

function trimLine(line) {
  let a = 0;
  let b = line.length;
  while (a < b && isSpaceTab(line[a])) a++;
  while (b > a && isSpaceTab(line[b - 1])) b--;
  return line.slice(a, b);
}

function isBlank(line) {
  for (let i = 0; i < line.length; i++) if (!isSpaceTab(line[i])) return false;
  return true;
}

const isLangChar = (c) =>
  (c >= 'A' && c <= 'Z') || (c >= 'a' && c <= 'z') || (c >= '0' && c <= '9') || c === '_' || c === '+' || c === '-';

/** A fence-open line's language, or null. */
function fenceLang(line) {
  if (!line.startsWith('```')) return null;
  let j = 3;
  while (j < line.length && isLangChar(line[j])) j++;
  const lang = line.slice(3, j);
  while (j < line.length && isSpaceTab(line[j])) j++;
  return j === line.length ? lang : null;
}

/** Whether the line closes a fence. */
function isFenceClose(line) {
  if (!line.startsWith('```')) return false;
  let j = 3;
  while (j < line.length && isSpaceTab(line[j])) j++;
  return j === line.length;
}

/** A heading line's level and text, or null. */
function headingOf(line) {
  if (line[0] !== '#') return null;
  let n = 0;
  while (n < line.length && line[n] === '#') n++;
  if (n === 0 || n > 6) return null;
  if (n >= line.length || !isSpaceTab(line[n])) return null;
  let k = n;
  while (k < line.length && isSpaceTab(line[k])) k++;
  let e = line.length;
  while (e > k && isSpaceTab(line[e - 1])) e--;
  const text = line.slice(k, e);
  return text === '' ? null : { depth: n, text };
}

/** Whether the line is a thematic break. */
function isHr(line) {
  if (line.length < 3) return false;
  const head = line.slice(0, 3);
  if (head !== '---' && head !== '***') return false;
  let j = 3;
  while (j < line.length && isSpaceTab(line[j])) j++;
  return j === line.length;
}

/** Whether `line` ends a paragraph: a blank line, a fence, a heading or a thematic break. */
function endsParagraph(line) {
  if (line.length === 0) return true;
  const c0 = line[0];
  if (c0 === ' ' || c0 === '\t') return isBlank(line);
  if (c0 === '`') return fenceLang(line) !== null;
  if (c0 === '#') return headingOf(line) !== null;
  if (c0 === '-' || c0 === '*') return isHr(line);
  return false;
}

/** A list item's shape: { ordered, start?, text }, or null when the line opens no list item. */
function listMatch(line) {
  if (line[1] === ' ' && (line[0] === '-' || line[0] === '*')) return { ordered: false, text: line.slice(2) };
  const c0 = line.charCodeAt(0);
  if (c0 < 48 || c0 > 57) return null;
  let j = 0;
  while (j < line.length && line.charCodeAt(j) >= 48 && line.charCodeAt(j) <= 57) j++;
  if (j === 0 || j > 9) return null;
  if (line[j] !== '.' || line[j + 1] !== ' ') return null;
  return { ordered: true, start: Number(line.slice(0, j)), text: line.slice(j + 2) };
}

const CONTINUED = /^ {2,}\S/;

/** The characters a backslash escapes. */
const ESCAPABLE = new Set(['\\', '`', '*', '_', '[', ']', '(', ')', '#', '+', '-', '.', '!', '>']);

/** The first index from `from` where `s` holds `what` outside a backslash escape, or -1. */
function findUnescaped(s, what, from) {
  for (let j = from; j <= s.length - what.length; j++) {
    if (s[j] === '\\' && j + 1 < s.length && ESCAPABLE.has(s[j + 1])) {
      j++;
      continue;
    }
    if (s.startsWith(what, j)) return j;
  }
  return -1;
}

/** The first single * from `from` (one whose run is not **), outside an escape, or -1. */
function findSingleStar(s, from) {
  for (let j = from; j < s.length; j++) {
    const c = s[j];
    if (c === '\\' && j + 1 < s.length && ESCAPABLE.has(s[j + 1])) {
      j++;
      continue;
    }
    if (c !== '*') continue;
    if (s[j + 1] === '*') {
      j++;
      continue;
    }
    return j;
  }
  return -1;
}

/**
 * `s` rendered inline; `env.link(target)` is a link's href. Identical output
 * to the reference's inline(). The scan for the next special character is
 * done by one regular expression (its C++ scan), so plain runs are copied
 * whole and never walked one character at a time; only the characters the
 * escape table names are ever rewritten.
 *
 * `i` is the start of the plain run now open. A special character that turns
 * out to be literal is left inside that run: the scan simply moves on past
 * it (the expression's own lastIndex), and the run is copied whole when the
 * next real construct is found or at the end.
 */
const INLINE_SPECIAL = /[\\`*\[&<>"']/g;

function inline(s, env) {
  let out = '';
  let i = 0;
  INLINE_SPECIAL.lastIndex = 0;
  let m;
  while ((m = INLINE_SPECIAL.exec(s)) !== null) {
    const j = m.index;
    const c = s[j];
    if (c === '\\') {
      if (j + 1 < s.length && ESCAPABLE.has(s[j + 1])) {
        // The backslash is dropped and the escaped character is written as
        // itself (none of the escapable characters needs HTML escaping);
        // the scan resumes past both, so the escaped character is never
        // re-read as a mark of its own.
        if (j > i) out += s.slice(i, j);
        out += s[j + 1];
        i = j + 2;
        INLINE_SPECIAL.lastIndex = i;
      }
      // Else not an escape: the backslash stays in the plain run.
      continue;
    }
    if (c === '`') {
      const k = s.indexOf('`', j + 1);
      if (k > j + 1) {
        if (j > i) out += s.slice(i, j);
        out += `<code>${escapeHtml(s.slice(j + 1, k))}</code>`;
        i = k + 1;
        INLINE_SPECIAL.lastIndex = i;
      }
      // Else no closer: the backtick stays in the plain run.
      continue;
    }
    if (c === '*') {
      if (s[j + 1] === '*') {
        const k = findUnescaped(s, '**', j + 2);
        if (k > j + 2) {
          if (j > i) out += s.slice(i, j);
          out += `<strong>${inline(s.slice(j + 2, k), env)}</strong>`;
          i = k + 2;
          INLINE_SPECIAL.lastIndex = i;
        } else {
          // No closer (or nothing between): both stars are literal, and
          // the scan resumes past both, so the second star is never
          // re-read as a fresh opener of its own.
          INLINE_SPECIAL.lastIndex = j + 2;
        }
        // In both cases the stars stay in the plain run.
        continue;
      }
      const k = findSingleStar(s, j + 1);
      if (k > j + 1) {
        if (j > i) out += s.slice(i, j);
        out += `<em>${inline(s.slice(j + 1, k), env)}</em>`;
        i = k + 1;
        INLINE_SPECIAL.lastIndex = i;
      }
      // Else no closer: the star stays in the plain run.
      continue;
    }
    if (c === '[') {
      const k = findUnescaped(s, ']', j + 1);
      const n = k !== -1 && s[k + 1] === '(' ? s.indexOf(')', k + 2) : -1;
      const target = n === -1 ? '' : s.slice(k + 2, n);
      if (target !== '' && !/\s/.test(target)) {
        if (j > i) out += s.slice(i, j);
        out += `<a href="${escapeHtml(env.link(target))}">${inline(s.slice(j + 1, k), env)}</a>`;
        i = n + 1;
        INLINE_SPECIAL.lastIndex = i;
      }
      // Else not a link: the bracket stays in the plain run.
      continue;
    }
    // One of & < > " ': escaped, never left in a plain run.
    if (j > i) out += s.slice(i, j);
    out += ESCAPES[c];
    i = j + 1;
    INLINE_SPECIAL.lastIndex = i;
  }
  if (i < s.length) out += s.slice(i);
  return out;
}

/**
 * `lines` from `start` rendered: its HTML (each block on its own lines, a
 * "\n" after the last), its table of contents and its excerpt. One pass, no
 * token array. `words` counts the body's words (for reading_minutes).
 */
function renderMarkdownLines(lines, start, env) {
  const ids = new Set();
  const blocks = [];
  const toc = [];
  let excerpt = null;
  let words = 0;
  const WORD = /\S+/g;
  let i = start;
  while (i < lines.length) {
    const line = lines[i];
    // Block dispatch on the first character: a fence, heading, break, quote
    // or list item can only open on its own first character, so most lines
    // are classified by one comparison instead of a battery of regexes.
    const c0 = line.length === 0 ? '' : line[0];
    if (c0 === '') {
      i++;
      continue;
    }
    if (c0 === ' ' || c0 === '\t') {
      if (isBlank(line)) {
        i++;
        continue;
      }
      // An indented line is paragraph text, never code: fall through.
    } else if (c0 === '`') {
      const lang = fenceLang(line);
      if (lang !== null) {
        const body = [];
        i++;
        while (i < lines.length && !isFenceClose(lines[i])) body.push(lines[i++]);
        i++;
        const cls = lang === '' ? '' : ` class="language-${escapeHtml(lang)}"`;
        blocks.push(`<pre><code${cls}>${body.map((l) => `${escapeHtml(l)}\n`).join('')}</code></pre>`);
        continue;
      }
      // Not a fence: fall through to a paragraph.
    } else if (c0 === '#') {
      const heading = headingOf(line);
      if (heading !== null) {
        const id = uniqueSlug(slugify(heading.text), ids);
        const html = inline(heading.text, env);
        blocks.push(`<h${heading.depth} id="${id}">${html}</h${heading.depth}>`);
        if (heading.depth === 2 || heading.depth === 3) toc.push({ level: heading.depth, id, html });
        i++;
        continue;
      }
      // Not a heading: fall through to a paragraph.
    } else if (c0 === '-' || c0 === '*') {
      if (isHr(line)) {
        blocks.push('<hr>');
        i++;
        continue;
      }
      const first = listMatch(line);
      if (first !== null) {
        const isOrdered = first.ordered;
        const items = [];
        const startNum = isOrdered ? first.start : 1;
        while (i < lines.length) {
          const m = listMatch(lines[i]);
          if (m !== null && m.ordered === isOrdered) {
            items.push([trimLine(m.text)]);
            i++;
          } else if (CONTINUED.test(lines[i])) {
            items[items.length - 1].push(trimLine(lines[i]));
            i++;
          } else break;
        }
        const tag = isOrdered ? 'ol' : 'ul';
        const open = isOrdered && startNum !== 1 ? `<ol start="${startNum}">` : `<${tag}>`;
        blocks.push(`${open}\n${items.map((item) => `<li>${inline(item.join('\n'), env)}</li>\n`).join('')}</${tag}>`);
        continue;
      }
      // Not a list: fall through to a paragraph.
    } else if (c0 === '>') {
      const body = [];
      while (i < lines.length && lines[i][0] === '>') body.push(lines[i++].replace(/^> ?/, ''));
      const kept = body.map(trimLine).filter((l) => l !== '');
      blocks.push(kept.length === 0 ? '<blockquote>\n</blockquote>' : `<blockquote>\n<p>${inline(kept.join('\n'), env)}</p>\n</blockquote>`);
      continue;
    } else if (c0 >= '0' && c0 <= '9') {
      const first = listMatch(line);
      if (first !== null) {
        const isOrdered = first.ordered;
        const items = [];
        const startNum = isOrdered ? first.start : 1;
        while (i < lines.length) {
          const m = listMatch(lines[i]);
          if (m !== null && m.ordered === isOrdered) {
            items.push([trimLine(m.text)]);
            i++;
          } else if (CONTINUED.test(lines[i])) {
            items[items.length - 1].push(trimLine(lines[i]));
            i++;
          } else break;
        }
        const tag = isOrdered ? 'ol' : 'ul';
        const open = isOrdered && startNum !== 1 ? `<ol start="${startNum}">` : `<${tag}>`;
        blocks.push(`${open}\n${items.map((item) => `<li>${inline(item.join('\n'), env)}</li>\n`).join('')}</${tag}>`);
        continue;
      }
      // Not a list: fall through to a paragraph.
    }
    const body = [trimLine(line)];
    i++;
    while (i < lines.length && !endsParagraph(lines[i])) body.push(trimLine(lines[i++]));
    const text = body.join('\n');
    const html = inline(text, env);
    if (excerpt === null) excerpt = html;
    blocks.push(`<p>${html}</p>`);
  }
  // Words of the whole body: a word never spans a line, so per-line counts add up.
  // Counted by hand for ASCII lines (the whitespace the reference's \S
  // names there is exactly space, tab, \n, \r, \v and \f); any line holding
  // a character outside ASCII falls back to the reference's own expression,
  // so Unicode spaces are still counted exactly as it counts them.
  for (let k = start; k < lines.length; k++) {
    const line = lines[k];
    let lw = 0;
    let inWord = false;
    let bad = false;
    for (let p = 0; p < line.length; p++) {
      if (line.charCodeAt(p) >= 128) {
        bad = true;
        break;
      }
      const ch = line[p];
      if (ch === ' ' || ch === '\t' || ch === '\n' || ch === '\r' || ch === '\v' || ch === '\f') inWord = false;
      else if (!inWord) {
        inWord = true;
        lw++;
      }
    }
    if (bad) {
      WORD.lastIndex = 0;
      lw = 0;
      let m;
      while ((m = WORD.exec(line)) !== null) lw++;
    }
    words += lw;
  }
  return { html: blocks.map((b) => `${b}\n`).join(''), toc, excerpt: excerpt ?? '', words };
}

